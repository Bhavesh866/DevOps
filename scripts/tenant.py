#!/usr/bin/env python3
"""Tenant fleet tool: one YAML file per stack in tenants/ is the source of truth.

  validate  check every tenant file against policy (residency, CIDRs, sizing)
  render    write infra/live/<name>/ and platform/tenants/<name>/ from the files
  check     validate, then fail if the committed rendered files are stale (CI)
  rings     print the rollout order as JSON (ring 0 = shared first)

Onboarding a tenant = a pull request adding tenants/<name>.yaml plus the output
of `render`. CI runs `check`; a reviewer approves; merge triggers the stack.
"""
import filecmp
import ipaddress
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TENANTS = ROOT / "tenants"
APPROVED = {
    "eu": {"eu-central-1", "eu-west-1", "eu-west-2", "eu-west-3", "eu-north-1", "eu-south-1"},
    "us": {"us-east-1", "us-east-2", "us-west-1", "us-west-2"},
}
# Terraform state for a stack lives in a bucket in the same residency zone.
STATE = {
    "eu": ("continuity-tfstate-eu", "eu-central-1"),
    "us": ("continuity-tfstate-us", "us-east-1"),
}
SUPPORTED_CLOUDS = {"aws"}  # extended by the second-cloud change request
NAME = re.compile(r"^[a-z][a-z0-9-]{1,30}$")


def load():
    tenants = []
    for path in sorted(TENANTS.glob("*.yaml")):
        data = yaml.safe_load(path.read_text())
        data["_file"] = path.name
        tenants.append(data)
    return tenants


def validate(tenants):
    errors = []
    seen = {}
    for t in tenants:
        f = t["_file"]
        name = t.get("name", "")
        if not NAME.match(name):
            errors.append(f"{f}: invalid name {name!r}")
        if f != f"{name}.yaml":
            errors.append(f"{f}: file name must be {name}.yaml")
        if name in seen:
            errors.append(f"{f}: duplicate name {name}")
        seen[name] = t
        if t.get("cloud") not in SUPPORTED_CLOUDS:
            errors.append(f"{f}: cloud {t.get('cloud')!r} not supported (allowed: {sorted(SUPPORTED_CLOUDS)})")
        if t.get("tier") not in ("shared", "dedicated"):
            errors.append(f"{f}: tier must be shared or dedicated")
        ring = t.get("ring")
        if not isinstance(ring, int) or ring < 0:
            errors.append(f"{f}: ring must be a non-negative integer")
        elif (t.get("tier") == "shared") != (ring == 0):
            errors.append(f"{f}: ring 0 is reserved for, and required by, the shared stack")
        residency, region = t.get("residency"), t.get("region")
        if residency not in APPROVED:
            errors.append(f"{f}: residency must be one of {sorted(APPROVED)}")
        elif region not in APPROVED[residency]:
            errors.append(f"{f}: region {region} is not approved for residency {residency}")
        try:
            net = ipaddress.ip_network(t.get("vpc_cidr", ""), strict=True)
            if net.prefixlen != 16:
                errors.append(f"{f}: vpc_cidr must be a /16")
            t["_net"] = net
        except ValueError:
            errors.append(f"{f}: invalid vpc_cidr {t.get('vpc_cidr')!r}")
        s = t.get("sizing", {})
        if s.get("api_min", 0) < 3:
            errors.append(f"{f}: api_min must be >= 3 (PDB minAvailable 2 + one disruption)")
        if s.get("api_max", 0) < s.get("api_min", 0):
            errors.append(f"{f}: api_max < api_min")
        if s.get("app_nodes_min", 0) < 3 and t.get("tier") == "dedicated":
            errors.append(f"{f}: dedicated stacks need app_nodes_min >= 3 (one per AZ for 99.95%)")
    nets = [(t["name"], t["_net"]) for t in tenants if "_net" in t]
    for i, (a, na) in enumerate(nets):
        for b, nb in nets[i + 1:]:
            if na.overlaps(nb):
                errors.append(f"CIDR overlap between {a} ({na}) and {b} ({nb})")
    return errors


def subnets(net):
    private = list(net.subnets(new_prefix=19))[:3]
    public = list(list(net.subnets(new_prefix=19))[-1].subnets(new_prefix=24))[:3]
    return [str(n) for n in private], [str(n) for n in public]


def hcl_list(items):
    return "[" + ", ".join(f'"{i}"' for i in items) + "]"


def hcl_assignments(pairs):
    """Aligned `key = value` lines, identical to `terraform fmt` output."""
    width = max(len(k) for k, _ in pairs)
    return "".join(f"{k.ljust(width)} = {v}\n" for k, v in pairs)


def render_tenant(t, out):
    name, s = t["name"], t["sizing"]
    private, public = subnets(t["_net"])
    bucket, state_region = STATE[t["residency"]]
    live = out / "infra" / "live" / name
    live.mkdir(parents=True, exist_ok=True)
    header = f"# GENERATED by scripts/tenant.py from tenants/{name}.yaml - do not edit.\n"
    (live / "terraform.tfvars").write_text(header + hcl_assignments([
        ("aws_region", f'"{t["region"]}"'),
        ("environment", '"prod"'),
        ("tenant", f'"{name}"'),
        ("residency", f'"{t["residency"]}"'),
        ("vpc_cidr", f'"{t["vpc_cidr"]}"'),
        ("private_subnet_cidrs", hcl_list(private)),
        ("public_subnet_cidrs", hcl_list(public)),
        ("eks_cluster_name", f'"{name}"'),
        ("app_nodes_min", s["app_nodes_min"]),
        ("app_nodes_max", s["app_nodes_max"]),
        ("db_instance_class", f'"{s["db_instance_class"]}"'),
    ]))
    (live / "backend.hcl").write_text(header + hcl_assignments([
        ("bucket", f'"{bucket}"'),
        ("key", f'"{name}/terraform.tfstate"'),
        ("region", f'"{state_region}"'),
    ]))

    overlay = out / "platform" / "tenants" / name
    overlay.mkdir(parents=True, exist_ok=True)
    (overlay / "kustomization.yaml").write_text(header + yaml.safe_dump({
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "resources": ["../../overlays/aws"],
        "labels": [{"pairs": {"tenant": name, "tier": t["tier"]}, "includeTemplates": True}],
        "patches": [
            {"target": {"kind": "HorizontalPodAutoscaler", "name": "api"},
             "patch": yaml.safe_dump([
                 {"op": "replace", "path": "/spec/minReplicas", "value": s["api_min"]},
                 {"op": "replace", "path": "/spec/maxReplicas", "value": s["api_max"]}])},
            {"target": {"kind": "ScaledObject", "name": "worker"},
             "patch": yaml.safe_dump([
                 {"op": "replace", "path": "/spec/maxReplicaCount", "value": s["workers_max"]}])},
            {"target": {"kind": "ExternalSecret", "name": "app-secrets"},
             "patch": yaml.safe_dump([
                 {"op": "replace", "path": "/spec/dataFrom/0/extract/key",
                  "value": f"{name}/prod/app-secrets"}])},
        ],
    }, sort_keys=False))


def render(tenants, out):
    for sub in ("infra/live", "platform/tenants"):
        shutil.rmtree(out / sub, ignore_errors=True)
    for t in tenants:
        render_tenant(t, out)


def same_tree(a, b):
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.diff_files or cmp.funny_files:
        return False
    return all(same_tree(Path(a) / d, Path(b) / d) for d in cmp.common_dirs)


def main(cmd):
    tenants = load()
    errors = validate(tenants)
    if errors:
        print("\n".join(f"ERROR: {e}" for e in errors))
        return 1
    if cmd == "validate":
        print(f"{len(tenants)} tenant definitions valid")
    elif cmd == "render":
        render(tenants, ROOT)
        print(f"rendered {len(tenants)} stacks")
    elif cmd == "check":
        with tempfile.TemporaryDirectory() as tmp:
            render(tenants, Path(tmp))
            for sub in ("infra/live", "platform/tenants"):
                if not (ROOT / sub).exists() or not same_tree(Path(tmp) / sub, ROOT / sub):
                    print(f"ERROR: {sub} is stale; run `python3 scripts/tenant.py render` and commit")
                    return 1
        print(f"{len(tenants)} tenant definitions valid; rendered files up to date")
    elif cmd == "rings":
        rings = {}
        for t in tenants:
            rings.setdefault(t["ring"], []).append(t["name"])
        print(json.dumps([{"ring": r, "stacks": sorted(n)} for r, n in sorted(rings.items())]))
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else ""))
